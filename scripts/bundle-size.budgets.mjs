/**
 * Бюджеты размера — данными, отдельно от механики замера.
 *
 * Пороги стоят с запасом около 15% от замера на 2.6.0: бюджет впритык краснеет
 * от любой правки и через месяц его начинают двигать не глядя.
 *
 * **Поднятие бюджета — отдельная строка в MR с объяснением, что именно
 * выросло.** Бюджет, который двигают заодно с правкой компонента, не сторожит
 * ничего: он лишь записывает постфактум то, что уже случилось.
 */

