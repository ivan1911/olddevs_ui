/**
 * Значение по брейкпойнтам кита → классы Tailwind.
 *
 * Общий механизм для пропов вида «одно значение или своё на каждой ширине
 * экрана»: `columns` у `Grid`, `slidesPerView` у `Carousel`. Модуль знает только
 * брейкпойнты и правило разбора; КЛАССЫ ПРИНОСИТ КОМПОНЕНТ своим словарём.
 *
 * Почему словарь, а не сборка строки (`` `${bp}:grid-cols-${n}` ``): Tailwind
 * сканирует исходники как текст и не исполняет код. Класс, склеенный в
 * рантайме, не попадёт в CSS, и сборка при этом пройдёт без предупреждения —
 * компонент просто окажется без раскладки. Поэтому каждый класс со своим
 * префиксом написан в словаре компонента целиком, а здесь только выбирается.
 *
 * Брейкпойнты — штатные Tailwind 4, и ровно те, на которых схлопывается кит:
 * `sm` (640) у `FormLayout`, `md` (768) у `AppShell`, `lg` (1024) у раскладок
 * страниц. Своих значений в `styles.css` кит не задаёт, поэтому префикс здесь
 * и медиазапрос у потребителя совпадают по построению. `base` — без префикса,
 * то есть с нуля: отсчёт mobile-first, как у самого Tailwind.
 *
 * Медиазапрос, а не `matchMedia`: раскладка, зависящая от JS, до гидратации
 * показывает неверную (ADR-0018), а класс работает с первого кадра и на сервере.
 */

/** Брейкпойнты по возрастанию ширины. Порядок важен: старший перекрывает младший. */
export const BREAKPOINTS = ["base", "sm", "md", "lg", "xl"] as const;

export type Breakpoint = (typeof BREAKPOINTS)[number];

/**
 * Одно значение на всех ширинах или своё с каждого брейкпойнта.
 *
 * Объект читается как в Tailwind: значение действует с указанной ширины и
 * выше, пока его не перекроет следующий ключ. Пропущенный ключ наследует
 * младший; пропущенный `base` значит «без класса» — что это даёт, решает
 * компонент (у сетки — одна колонка, как у любого `display: grid`).
 */
export type Responsive<T extends PropertyKey> = T | Partial<Record<Breakpoint, T>>;

/**
 * Словарь компонента: для каждого брейкпойнта — класс на каждое значение.
 *
 * Тип требует ВСЕ брейкпойнты и ВСЕ значения: пропущенная клетка была бы
 * значением, которое тип пропускает, а CSS не знает. Значения у `base` без
 * префикса, у остальных — с префиксом брейкпойнта (`md:grid-cols-3`).
 */
export type ResponsiveClassMap<T extends PropertyKey> = Record<Breakpoint, Record<T, string>>;

/**
 * Разворачивает значение в классы по словарю.
 *
 * Скаляр — это `base`: без префикса класс действует на любой ширине. Пустое
 * значение (`undefined`) даёт пустую строку, и компонент сам решает, что
 * считать умолчанием.
 */
export function responsiveClasses<T extends PropertyKey>(
  value: Responsive<T> | undefined,
  map: ResponsiveClassMap<T>
): string {
  if (value == null) return "";
  // `T` — число или строка, поэтому объект здесь однозначно «по брейкпойнтам».
  const byBreakpoint: Partial<Record<Breakpoint, T>> =
    typeof value === "object" ? value : { base: value };

  // Значение вне словаря (потребитель на JS, без проверки типов) не даёт
  // класса вовсе, а не строку `undefined` в разметке.
  return BREAKPOINTS.flatMap((breakpoint) => {
    const at = byBreakpoint[breakpoint];
    const cls = at == null ? undefined : (map[breakpoint][at] as string | undefined);
    return cls ? [cls] : [];
  }).join(" ");
}
