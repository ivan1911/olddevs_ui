/**
 * Оболочка поля ввода: рамка, фокус, выключенное состояние.
 *
 * Вынесено из `TextControl` в момент появления `NumberInput` — второго
 * компонента с такой же оболочкой. Копипаст этих строк разошёлся бы: во фронте
 * до пакета так и вышло — пять рукописных полей поиска красили фокус в `--tg`,
 * тогда как обычные поля через `TextControl` — в `--accent-strong`, и увидеть
 * расхождение можно было, только открыв пять файлов рядом.
 *
 * ВАЖНО про склейку `+` ниже — она безопасна, и это не то же самое, что
 * запрещено в `variants.ts`. Tailwind сканирует исходники как ТЕКСТ и ищет в
 * нём кандидатов: каждое имя класса здесь присутствует в файле целиком, внутри
 * литерала, а `+` только соединяет готовые строки. Запрещено другое — собирать
 * само ИМЯ класса (`` `hover:${t.bg}` ``): такого текста в файле нет, и в CSS
 * он не попадёт молча, без ошибки сборки. Сторожит `tests/class-coverage.test.ts`.
 */

import { INVALID_BORDER_CLASS } from "./variants.js";

/**
 * Рамка живёт на оболочке, а не на самом поле. Разделение не косметическое:
 * оно позволяет положить внутрь иконку или счётчик, не воюя с браузерным
 * оформлением поля.
 *
 * Подсветка фокуса — через `focus-within`, и цвет берётся из `--accent-strong`,
 * а не из `--accent`: индикатор фокуса это не-текст под порогом 3:1, а
 * `--accent` рассчитан на белый текст поверх.
 *
 * Выключенное состояние гасит ОБОЛОЧКУ, а не поле: `disabled:opacity-50` на
 * самом поле приглушил бы только текст, оставив рамку такой же яркой, как у
 * соседнего рабочего поля.
 *
 * Селектор адресует именно поле (`has-[input:disabled]`, `has-[textarea:disabled]`),
 * а не любого выключенного потомка (`has-[:disabled]`, как было до появления
 * `NumberInput`). Разница не теоретическая: в оболочке числового поля стоят ещё
 * две кнопки ступеней, и на границе `min`/`max` одна из них законно выключена —
 * прежний селектор гасил из-за неё всё поле вместе со значением. Поймал аудит
 * axe: унаследованная прозрачность роняла контраст значения с 4.5 до 4.07.
 *
 * НЕВАЛИДНОСТЬ КРАСИТ ТУ ЖЕ ОБОЛОЧКУ, И ИСТОЧНИКОВ У НЕЁ ДВА. У контролов
 * react-aria признак висит атрибутом `data-invalid` на самой оболочке — его
 * ловит вариант `invalid:` из плагина. У полей на нативных `input`/`textarea`
 * оболочка — обычный `div`, на котором ловить нечего: там признак живёт на
 * самом поле в `aria-invalid`, и оболочка дотягивается до него через `has-`.
 * Одного селектора не хватало: до этой правки `INVALID_BORDER_CLASS` был
 * объявлен, но применён ровно в одном месте — вручную в `NumberInput`, — и
 * `TextControl`, `Combobox`, `TagInput` и построенный на первом `SearchControl`
 * показать ошибку не умели вовсе.
 *
 * Порядок в строке значим: `invalid:` стоит ПОСЛЕ `focus-within:`, поэтому у
 * поля в фокусе с ошибкой рамка остаётся красной. Так вело себя числовое поле
 * до переноса правила сюда, и менять это заодно с переносом не стоит.
 */
export const FIELD_SHELL_CLASS =
  "border-line bg-bg-2 rounded-control border px-3 shadow-[var(--shadow-1)] " +
  "transition-[border-color,box-shadow] duration-150 " +
  "focus-within:border-accent-strong focus-within:ring-[3px] focus-within:ring-[color:var(--focus-ring)] " +
  INVALID_BORDER_CLASS +
  " has-[input[aria-invalid=true]]:border-danger-strong " +
  "has-[textarea[aria-invalid=true]]:border-danger-strong " +
  "has-[input:disabled]:cursor-not-allowed has-[input:disabled]:opacity-50 " +
  "has-[textarea:disabled]:cursor-not-allowed has-[textarea:disabled]:opacity-50";

/**
 * Само поле обнулено полностью: без этого Safari и Chrome рисуют разное.
 * Глобальное правило `:focus-visible` в `styles.css` гасится атрибутом
 * `data-disable-focus-ring` на элементе — контур вокруг поля здесь лишний,
 * подсветку даёт оболочка.
 *
 * `leading-5` — не косметика, а объявленная высота строчного бокса контрола,
 * и она же держит общую высоту в 42px: `20 + 2×10 отступа + 2 рамки`. Без неё
 * бокс получался из унаследованного множителя `1.5` при `text-[13px]`, то есть
 * 19.5px, а поле — 41.5px. Число случайное, и совпадать с ним чему-то ещё
 * нечем: триггер `Select` с картинкой в 22px давал 44px и расходился с
 * соседним полем на пару пикселей. Теперь высота задана, а не выведена, и
 * `Select` пришёл к тем же 42 — тем же `leading-5` на триггере.
 *
 * Оговорка: объявление живёт, пока потребитель не пришлёт свой размер шрифта.
 * `cn` — это `twMerge`, и чужой `text-*` в `className` вытесняет пару
 * `text-[13px] leading-5` целиком. Со ступенями шкалы это безвредно — у них
 * строчный бокс задан свой (`text-sm` — те же 13/20), — а вот произвольный
 * `text-[15px]` вернёт высоту к выведенной из множителя.
 */
export const FIELD_INPUT_CLASS =
  "text-fg-0 w-full [appearance:none] border-0 bg-transparent px-0 py-[10px] text-[13px] leading-5 " +
  "shadow-none outline-none [-webkit-tap-highlight-color:transparent] " +
  "focus:border-0 focus:ring-0 focus:outline-none focus-visible:ring-0 focus-visible:outline-none " +
  "disabled:cursor-not-allowed";

/**
 * Компактная ступень поля: 36 пикселей вместо 42.
 *
 * ОДНО ЗНАЧЕНИЕ ВЕРТИКАЛЬНОГО ОТСТУПА, и больше ничего: рамка, скругление,
 * тень, шрифт и строчный бокс те же. `20 + 2×7 + 2 = 36` — ровно рост
 * `Button size="md"` и пилюли-триггера `Select`, то есть число, которое кит уже
 * дважды выбрал сам. В одной строке панели управления поле до этого выпадало из
 * ряда в одиночку.
 *
 * ЗАЧЕМ СТУПЕНЬ, ЕСЛИ ВЫСОТА И ТАК ДОСТИЖИМА. Достижима: `className` уходит в
 * конец `cn(FIELD_INPUT_CLASS, …, className)`, а `cn` — это `twMerge`, и `py-0`
 * снаружи вытесняет `py-[10px]`. Именно так и сделано у двух потребителей — с
 * двумя разными числами (34 и 36) и двумя разными шрифтами. Довод тот же, что у
 * самого `SearchControl`: пять рукописных полей поиска во фронте красили фокус
 * не тем цветом, и увидеть это можно было, только открыв пять файлов рядом.
 *
 * Зона нажатия остаётся выше порога: 36 — в полтора раза больше минимальной
 * цели WCAG 2.5.8.
 */
export const FIELD_INPUT_COMPACT_CLASS = "py-[7px]";

