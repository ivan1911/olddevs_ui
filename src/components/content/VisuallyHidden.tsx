/**
 * Содержимое для скринридера, невидимое глазами.
 *
 * Реэкспорт react-aria, а не своя реализация, и это осознанно: «спрятать, но
 * оставить доступным» — приём, который легко написать неправильно и не
 * заметить. `display: none` и `visibility: hidden` убирают узел из дерева
 * доступности вовсе; `width: 0` схлопывает текст в ничто и часть
 * скринридеров его пропускает; `text-indent: -9999px` ломает горизонтальную
 * прокрутку страницы в RTL.
 *
 * Правильный набор — квадрат 1×1 с `clip-path`, `overflow: hidden` и
 * `white-space: nowrap` — библиотека держит сама и правит вместе с
 * изменениями браузеров. Утилита `sr-only` из Tailwind делает то же самое и
 * применяется там, где хватает класса; компонент нужен, когда прятать надо
 * поддерево.
 *
 * ВНУТРИ СТРОКИ НУЖЕН `elementType="span"`. По умолчанию react-aria рисует
 * `<div>`, и вставка его в `<p>` или в заголовок даёт невалидную вложенность:
 * React пишет в консоль ошибку гидрации, а браузер разрывает абзац. Долго это
 * не замечалось — тесты были зелёными, предупреждение уезжало в stderr.
 */
